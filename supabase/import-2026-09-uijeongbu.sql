-- 선생님·아이 명단(의정부)과 잇기
imp2 as (
  select i.day::date as d, i.*, t.id as teacher_id, c.id as child_id
  from imp i
  left join teachers t on t.name = i.teacher
  left join lateral (
    select ch.id from children ch
    where ch.center = 'uijeongbu' and i.status = 'child' and ch.name = i.name
    order by coalesce(ch.number, 1), ch.created_at
    limit 1
  ) c on true
  where i.teacher <> '이원재'   -- 이원재 선생님은 9월에 수업하지 않았다(병가) — 엑셀에 있어도 넣지 않고, 있던 칸은 지운다
),
del as (
  delete from board_cells b
  where b.center = 'uijeongbu' and b.day between '2026-09-01' and '2026-09-30'
    and not exists (select 1 from imp2 x where x.teacher_id is not null and x.d = b.day and x.teacher_id = b.teacher_id and x.time = b.time and x.side = b.side)
  returning 1
),
cells as (
  insert into board_cells (center, day, teacher_id, time, side, status, child_id, name, payment, oral, absent, moved, note, updated_at)
  select 'uijeongbu', d, teacher_id, time, side, status, child_id, name, replace(payment, 'e', 'c'), false, absent, false, note, now()
  from imp2 where teacher_id is not null
  on conflict (center, day, teacher_id, time, side) do update
    set status = excluded.status, child_id = excluded.child_id, name = excluded.name, payment = excluded.payment, oral = false,
        kind = null, absent = excluded.absent, moved = false, note = excluded.note, updated_at = now()
  returning 1
),
pays as (
  insert into lesson_payments (child_id, day, time, teacher_id, center, method, note, confirmed)
  select distinct on (child_id, d, time) child_id, d, time, teacher_id, 'uijeongbu',
         case when payment like '%b%' then 'voucher' else 'kkumideun' end, null, true
  from imp2
  where status = 'child' and not absent and child_id is not null and teacher_id is not null and payment ~ '[bec]'
  order by child_id, d, time, side
  on conflict (child_id, day, time) do update
    set method = excluded.method, teacher_id = excluded.teacher_id, center = excluded.center, note = null, confirmed = true
  returning 1
)
select '지운 칸(엑셀에 없는 칸)' as 항목, count(*)::text as 값 from del
union all select '넣은 칸', count(*)::text from cells
union all select '결제 완료로 넣은 수업', count(*)::text from pays
union all select '의정부 명단에 없는 이름', coalesce(string_agg(distinct name, ', '), '없음') from imp2 where status = 'child' and child_id is null
union all select '선생님 명단에 없는 이름', coalesce(string_agg(distinct teacher, ', '), '없음') from imp2 where teacher_id is null;
