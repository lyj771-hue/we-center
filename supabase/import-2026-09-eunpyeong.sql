-- 선생님·아이 명단과 잇기 — 이름 앞 숫자는 번호(없으면 1). 명단에 "3김채현"처럼 숫자까지 이름으로 들어 있어도 찾는다
imp2 as (
  select i.day::date as d, i.*, t.id as teacher_id, c.id as child_id, coalesce(c.name, i.name) as show_name
  from imp i
  left join teachers t on t.name = i.teacher
  left join lateral (
    select ch.id, ch.name from children ch
    where coalesce(ch.center, 'eunpyeong') = 'eunpyeong' and i.status = 'child'
      and ((ch.name = i.name and coalesce(ch.number, 1) = coalesce(i.num, 1)) or (i.num is not null and ch.name = i.num::text || i.name))
    order by ch.created_at
    limit 1
  ) c on true
),
-- 1) 9월 은평 날짜별 칸 — 엑셀로 덮어쓰기: 엑셀에 없는 칸은 지우고, 있는 칸은 엑셀대로
del as (
  delete from board_cells b
  where b.center = 'eunpyeong' and b.day between '2026-09-01' and '2026-09-30'
    and not exists (select 1 from imp2 x where x.teacher_id is not null and x.d = b.day and x.teacher_id = b.teacher_id and x.time = b.time and x.side = b.side)
  returning 1
),
cells as (
  insert into board_cells (center, day, teacher_id, time, side, status, child_id, name, payment, oral, kind, absent, moved, note, updated_at)
  select 'eunpyeong', d, teacher_id, time, side, status, child_id,
         case when status = 'child' then case when child_id is null and num is not null then num::text || show_name else show_name end end,
         payment, oral, case when oral then 'oral' end, absent, false, null, now()
  from imp2 where teacher_id is not null
  on conflict (center, day, teacher_id, time, side) do update
    set status = excluded.status, child_id = excluded.child_id, name = excluded.name, payment = excluded.payment, oral = excluded.oral,
        kind = excluded.kind, absent = excluded.absent, moved = false, note = null, updated_at = now()
  returning 1
),
-- 2) 진행된 수업 [결제 완료] — 바우처·굳센·꿈이든
pays as (
  insert into lesson_payments (child_id, day, time, teacher_id, center, method, note, confirmed)
  select distinct on (child_id, d, time) child_id, d, time, teacher_id, 'eunpyeong',
         case when payment like '%b%' then 'voucher' when payment like '%e%' then 'gusen' else 'kkumideun' end, null, true
  from imp2
  where status = 'child' and not absent and child_id is not null and teacher_id is not null and payment ~ '[bec]'
  order by child_id, d, time, side
  on conflict (child_id, day, time) do update
    set method = excluded.method, teacher_id = excluded.teacher_id, center = excluded.center, note = null, confirmed = true
  returning 1
)
