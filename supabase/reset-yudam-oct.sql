create temp table t_kids on commit drop as
  select id from children where name = '김유담';
create temp table t_kid_b on commit drop as
  select id from children where name = '김유담B';
create temp table t_users on commit drop as
  select guardian_user_id as uid from children where name in ('김유담', '김유담B') and guardian_user_id is not null
  union
  select user_id from profiles where btrim(nickname) = '김유담' or btrim(coalesce(center_nickname, '')) = '김유담';

-- ── 1. 김유담 ─────────────────────────────────────────────
delete from lesson_payments where child_id in (select id from t_kids) and day <= date '2026-10-31';
